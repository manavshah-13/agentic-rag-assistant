import os
import re
from typing import List, Literal, TypedDict
from dotenv import load_dotenv
from pydantic import BaseModel, Field

from qdrant_client import QdrantClient
from sentence_transformers import SentenceTransformer, CrossEncoder
from tavily import TavilyClient

from langchain_groq import ChatGroq
from langchain_core.prompts import ChatPromptTemplate
from langgraph.graph import END, StateGraph, START

load_dotenv()

# ==========================================
# 1. INITIALIZE CLIENTS & MODELS
# ==========================================
embedder = SentenceTransformer("BAAI/bge-small-en-v1.5")
reranker = CrossEncoder("BAAI/bge-reranker-base")

qdrant_client = QdrantClient(
    url=os.getenv("QDRANT_URL"),
    api_key=os.getenv("QDRANT_API_KEY")
)
COLLECTION_NAME = "demo_collection"

tavily_client = TavilyClient(api_key=os.getenv("TAVILY_API_KEY"))

llm = ChatGroq(
    groq_api_key=os.getenv("GROQ_API_KEY"),
    model_name="qwen/qwen3.6-27b",
    temperature=0
)

# ==========================================
# 2. HELPER FUNCTIONS
# ==========================================
def clean_llm_output(raw_text: str) -> str:
    """Strip reasoning/thought tags generated by reasoning-centric models."""
    cleaned = re.sub(r"<think>.*?</think>", "", raw_text, flags=re.DOTALL)
    return cleaned.strip()

# ==========================================
# 3. DEFINE AGENT STATE
# ==========================================
class AgentState(TypedDict):
    question: str
    generation: str
    documents: List[str]

# ==========================================
# 4. DEFINE NODES
# ==========================================

# --- Node A: Retrieve Candidate Documents from Qdrant ---
def retrieve(state: AgentState):
    print("\n--- 🔎 NODE: RETRIEVING CANDIDATES (Top 4) FROM QDRANT ---")
    question = state["question"]
    
    query_vector = embedder.encode(question).tolist()
    search_response = qdrant_client.query_points(
        collection_name=COLLECTION_NAME,
        query=query_vector,
        limit=4
    )
    
    docs = [point.payload["text"] for point in search_response.points]
    return {"documents": docs, "question": question}

# --- Node B: Cross-Encoder Semantic Reranker ---
def rerank(state: AgentState):
    print("--- 🎯 NODE: SEMANTIC RERANKING (Cross-Encoder) ---")
    question = state["question"]
    documents = state["documents"]
    
    if not documents:
        return {"documents": [], "question": question}
    
    pairs = [[question, doc] for doc in documents]
    scores = reranker.predict(pairs)
    
    scored_docs = list(zip(documents, scores))
    scored_docs.sort(key=lambda x: x[1], reverse=True)
    
    top_docs = []
    for doc, score in scored_docs[:2]:
        print(f"  -> Rerank Score: {score:.4f} | \"{doc[:60]}...\"")
        top_docs.append(doc)
        
    return {"documents": top_docs, "question": question}

# --- Node C: Grade Retrieved Documents ---
class GradeDocument(BaseModel):
    binary_score: Literal["yes", "no"] = Field(
        description="Documents are relevant to the question, 'yes' or 'no'"
    )

structured_llm_grader = llm.with_structured_output(GradeDocument)

grader_prompt = ChatPromptTemplate.from_messages([
    ("system", "You are a grader assessing relevance of a retrieved document to a user question.\n"
               "If the document contains information to answer the question, grade 'yes', else 'no'."),
    ("human", "Retrieved document:\n\n{document}\n\nUser question: {question}")
])
doc_grader = grader_prompt | structured_llm_grader

def grade_documents(state: AgentState):
    print("--- ⚖️ NODE: CHECKING DOCUMENT RELEVANCE ---")
    question = state["question"]
    documents = state["documents"]
    
    filtered_docs = []
    for doc in documents:
        score = doc_grader.invoke({"question": question, "document": doc})
        if score.binary_score == "yes":
            print("  -> Document RELEVANT ✅")
            filtered_docs.append(doc)
        else:
            print("  -> Document NOT RELEVANT ❌")
            
    return {"documents": filtered_docs, "question": question}

# --- Node D: Web Search Fallback ---
def web_search(state: AgentState):
    print("--- 🌐 NODE: FALLBACK WEB SEARCH ---")
    question = state["question"]
    
    search_response = tavily_client.search(query=question, max_results=2)
    web_results = [res["content"] for res in search_response["results"]]
    
    return {"documents": web_results, "question": question}

# --- Node E: Generate Answer ---
def generate(state: AgentState):
    print("--- 🤖 NODE: GENERATING FINAL ANSWER ---")
    question = state["question"]
    documents = state["documents"]
    
    context = "\n\n".join(documents) if documents else "No relevant context found."
        
    prompt = f"""Use the context below to answer the question concisely and accurately.
    
Context:
{context}

Question: {question}
Answer:"""
    
    response = llm.invoke(prompt)
    return {"generation": clean_llm_output(response.content)}

# --- Node F: Direct Chat ---
def direct_chat(state: AgentState):
    print("\n--- 💬 NODE: DIRECT CHAT ---")
    question = state["question"]
    response = llm.invoke(question)
    return {"generation": clean_llm_output(response.content)}

# ==========================================
# 5. CONDITIONAL ROUTING
# ==========================================
class RouteQuery(BaseModel):
    datasource: Literal["vectorstore", "direct_chat"] = Field(..., description="Route query")

structured_llm_router = llm.with_structured_output(RouteQuery)
route_prompt = ChatPromptTemplate.from_messages([
    ("system", "Route questions about AI hardware, Groq, LPUs, GPUs, or Qdrant to 'vectorstore'. Otherwise 'direct_chat'."),
    ("human", "{question}")
])
question_router = route_prompt | structured_llm_router

def route_question(state: AgentState):
    print("\n--- 🚦 ROUTING INITIAL QUESTION ---")
    question = state["question"]
    source = question_router.invoke({"question": question})
    return "vectorstore" if source.datasource == "vectorstore" else "direct_chat"

def decide_to_generate(state: AgentState):
    print("--- 🔍 EVALUATING GRADED DOCUMENTS ---")
    if not state["documents"]:
        print("  -> Decision: No relevant context. Routing to WEB SEARCH 🌐")
        return "websearch"
    else:
        print("  -> Decision: Relevant context found. Routing to GENERATE 🤖")
        return "generate"

# ==========================================
# 6. BUILD & COMPILE GRAPH
# ==========================================
workflow = StateGraph(AgentState)

workflow.add_node("retrieve", retrieve)
workflow.add_node("rerank", rerank)
workflow.add_node("grade_documents", grade_documents)
workflow.add_node("web_search", web_search)
workflow.add_node("generate", generate)
workflow.add_node("direct_chat", direct_chat)

workflow.add_conditional_edges(
    START,
    route_question,
    {
        "vectorstore": "retrieve",
        "direct_chat": "direct_chat"
    }
)

workflow.add_edge("retrieve", "rerank")
workflow.add_edge("rerank", "grade_documents")

workflow.add_conditional_edges(
    "grade_documents",
    decide_to_generate,
    {
        "websearch": "web_search",
        "generate": "generate"
    }
)

workflow.add_edge("web_search", "generate")
workflow.add_edge("generate", END)
workflow.add_edge("direct_chat", END)

app = workflow.compile()

# ==========================================
# 7. EXECUTE TESTS
# ==========================================
if __name__ == "__main__":
    test_query = "How do LPUs compare to GPUs for batch size 1 inference workloads?"
    print(f"================== TEST: Detailed Reranked Query ==================")
    output = app.invoke({"question": test_query})
    print(f"\nFinal Response:\n{output['generation']}\n")